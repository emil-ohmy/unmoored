#!/usr/bin/env bash
# Build models into the Unity project.
#   tools/build-models.sh                  # everything in art/models/
#   tools/build-models.sh apprentice laden # just these (by file name)
# art/models/<category>/<name>.py builds from code; a <name>.blend without a .py is exported as-is.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BLENDER="${BLENDER:-/Applications/Blender.app/Contents/MacOS/Blender}"

shopt -s nullglob
wanted=("$@")
matches() {
  [[ ${#wanted[@]} -eq 0 ]] && return 0
  for w in "${wanted[@]}"; do [[ "$1" == "$w" ]] && return 0; done
  return 1
}

run() { # label, blender args...
  local label="$1"; shift
  if ! out="$("$BLENDER" "$@" 2>&1)"; then
    echo "FAILED $label"; echo "$out" | grep -E "Error|Traceback|line [0-9]+" | head -20; exit 1
  fi
  echo "$out" | grep -E "^\[[a-z_]+\]" || { echo "FAILED $label (no export)"; echo "$out" | tail -20; exit 1; }
}

for script in "$ROOT"/art/models/*/*.py; do
  name="$(basename "$script" .py)"
  matches "$name" || continue
  run "$name" -b --factory-startup --python-exit-code 1 --python "$ROOT/tools/blender/build_model.py" -- "$script"
done

for blend in "$ROOT"/art/models/*/*.blend; do
  name="$(basename "$blend" .blend)"
  base="${blend%.blend}"
  [[ -f "$base.py" || -f "${base%_*}.py" ]] && continue # generated by a script (or one of its variants); built above
  matches "$name" || continue
  run "$name" -b "$blend" --python-exit-code 1 --python "$ROOT/tools/blender/export_fbx.py"
done
